use schemars::{JsonSchema, schema_for};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::BTreeMap;

pub const PROTOCOL_MIN: u32 = 1;
pub const PROTOCOL_MAX: u32 = 1;

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
#[serde(untagged)]
pub enum RpcId {
    Number(i64),
    String(String),
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct RpcRequest {
    pub jsonrpc: String,
    pub id: RpcId,
    pub method: String,
    #[serde(default)]
    pub params: Value,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct RpcNotification {
    pub jsonrpc: String,
    pub method: String,
    #[serde(default)]
    pub params: Value,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct RpcError {
    pub code: i32,
    pub message: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub data: Option<Value>,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct RpcResponse {
    pub jsonrpc: String,
    pub id: RpcId,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub result: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<RpcError>,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct InitializeParams {
    pub protocol_version: u32,
    pub client_name: String,
    pub client_version: String,
    #[serde(default)]
    pub capabilities: BTreeMap<String, bool>,
    #[serde(default)]
    pub notifications: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ThreadStatus {
    Idle,
    Running,
    Paused,
    Interrupted,
    Failed,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct Thread {
    pub id: String,
    pub title: String,
    pub workspace: String,
    pub model: String,
    pub reasoning: String,
    pub permission_profile: String,
    pub status: ThreadStatus,
    pub pinned: bool,
    pub archived: bool,
    pub created_at: String,
    pub updated_at: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum TurnStatus {
    Running,
    Paused,
    Completed,
    Interrupted,
    Failed,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct Turn {
    pub id: String,
    pub thread_id: String,
    pub status: TurnStatus,
    pub started_at: String,
    pub completed_at: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ItemKind {
    UserMessage,
    AgentMessage,
    Reasoning,
    ToolCall,
    ToolOutput,
    CommandOutput,
    FileChange,
    Approval,
    Error,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct Item {
    pub id: String,
    pub turn_id: String,
    pub kind: ItemKind,
    pub content: Value,
    pub status: String,
    pub created_at: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct ProtocolDocument {
    pub requests: RpcRequest,
    pub notifications: RpcNotification,
    pub responses: RpcResponse,
    pub thread: Thread,
    pub turn: Turn,
    pub item: Item,
}

pub fn json_schema() -> Value {
    serde_json::to_value(schema_for!(ProtocolDocument)).expect("serialize schema")
}

pub fn typescript_bindings() -> String {
    r#"// Generated by cosaii-app-server generate-ts. Do not edit.
export type RpcId = number | string;
export interface RpcRequest { jsonrpc: '2.0'; id: RpcId; method: string; params?: unknown }
export interface RpcNotification { jsonrpc: '2.0'; method: string; params?: unknown }
export interface RpcError { code: number; message: string; data?: unknown }
export interface RpcResponse { jsonrpc: '2.0'; id: RpcId; result?: unknown; error?: RpcError }
export type ThreadStatus = 'idle'|'running'|'paused'|'interrupted'|'failed';
export type TurnStatus = 'running'|'paused'|'completed'|'interrupted'|'failed';
export type ItemKind = 'user_message'|'agent_message'|'reasoning'|'tool_call'|'tool_output'|'command_output'|'file_change'|'approval'|'error';
export interface InitializeParams { protocol_version:number; client_name:string; client_version:string; capabilities:Record<string,boolean>; notifications:string[] }
"#.to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn protocol_schema_contains_thread_turn_and_item_primitives() {
        let schema = json_schema().to_string();
        for expected in ["Thread", "Turn", "Item", "RpcRequest", "RpcResponse"] {
            assert!(schema.contains(expected), "schema omitted {expected}");
        }
    }

    #[test]
    fn generated_types_pin_json_rpc_shapes() {
        let types = typescript_bindings();
        assert!(types.contains("jsonrpc: '2.0'"));
        assert!(types.contains("item/toolCall") || types.contains("ItemKind"));
        assert_eq!(PROTOCOL_MIN, 1);
        assert_eq!(PROTOCOL_MAX, 1);
    }
}
